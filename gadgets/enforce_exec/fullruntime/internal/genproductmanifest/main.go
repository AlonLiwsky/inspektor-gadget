// Command genproductmanifest writes the exact map and program name sets of
// the shared product object (fullruntime shared_product_manifest.go), read
// from compiled product objects. Every object given must carry exactly the
// same sets; any difference is an error. Arguments are object paths; each
// argument is also split on commas and white space, so the comma-separated
// IG_ENFORCE_EXEC_PRODUCT_OBJECTS list the object tests take can be passed as
// one argument. It is run by hand, not by go generate: CI has no product
// objects.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"go/format"
	"maps"
	"os"
	"slices"
	"strings"
	"unicode"

	"github.com/cilium/ebpf"
)

func main() {
	out := flag.String("o", "shared_product_manifest.go", "output Go file")
	flag.Parse()
	var paths []string
	for _, arg := range flag.Args() {
		paths = append(paths, strings.FieldsFunc(arg, func(r rune) bool { return r == ',' || unicode.IsSpace(r) })...)
	}
	if err := run(*out, paths); err != nil {
		fmt.Fprintf(os.Stderr, "genproductmanifest: %v\n", err)
		os.Exit(1)
	}
}

func run(out string, paths []string) error {
	if len(paths) == 0 {
		return fmt.Errorf("no product objects (set IG_ENFORCE_EXEC_PRODUCT_OBJECTS)")
	}
	var mapNames, programNames []string
	var sums []string
	for k, path := range paths {
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		spec, err := ebpf.LoadCollectionSpecFromReader(bytes.NewReader(data))
		if err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
		m, p := slices.Sorted(maps.Keys(spec.Maps)), slices.Sorted(maps.Keys(spec.Programs))
		if k == 0 {
			mapNames, programNames = m, p
		} else if !slices.Equal(m, mapNames) || !slices.Equal(p, programNames) {
			return fmt.Errorf("%s: name sets differ from %s", path, paths[0])
		}
		sum := sha256.Sum256(data)
		sums = append(sums, hex.EncodeToString(sum[:]))
	}
	slices.Sort(sums)
	var b bytes.Buffer
	b.WriteString("// Copyright 2026 The Inspektor Gadget authors\n// SPDX-License-Identifier: Apache-2.0\n\n")
	b.WriteString("// Code generated by genproductmanifest; DO NOT EDIT.\n\n")
	b.WriteString("// Regenerate by hand (not via go generate: CI has no product objects):\n//\n//\tgo run ./internal/genproductmanifest -o shared_product_manifest.go <product objects>\n\npackage fullruntime\n\n")
	b.WriteString("// sharedProductManifestMaps and sharedProductManifestPrograms are the exact\n")
	b.WriteString("// map and program name sets of the shared product object, generated from\n")
	b.WriteString("// the product objects with sha256:\n")
	for _, sum := range sums {
		fmt.Fprintf(&b, "//   - %s\n", sum)
	}
	b.WriteString("//\n// Product admission refuses any other name set (validateSharedProductManifest).\n")
	writeList(&b, "sharedProductManifestMaps", mapNames)
	writeList(&b, "sharedProductManifestPrograms", programNames)
	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(out, src, 0o644)
}

func writeList(b *bytes.Buffer, name string, values []string) {
	fmt.Fprintf(b, "var %s = []string{\n", name)
	for _, v := range values {
		fmt.Fprintf(b, "\t%q,\n", v)
	}
	b.WriteString("}\n\n")
}
