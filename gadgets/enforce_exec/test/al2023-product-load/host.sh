# Host side of the AL2023 product object-load run (G035 plan sections 1 and 6).
#
#   host.sh build <run-dir>                 objects, layout, binaries -> <run-dir>/bundle
#   host.sh run   <run-dir> <lane> <tag>    one machine: guest.sh <tag> through lanes/<lane>.sh
#   host.sh judge <run-dir>                 judge every result; its exit code is the verdict
#   host.sh all   <run-dir> <lane> [tag...] build, run each tag (default: 6.12 6.18 unpinned), judge
#
#   lane                 qemu (lanes/qemu.sh) or ec2 (lanes/ec2.sh, refuses until step 3)
#   AL2023_PROFILES      PENDING D4, required (env.sh)
#   AL2023_NEG_SET       PENDING D5, required (env.sh)
#   AL2023_JUDGE_KERNELS groups the judge requires (default build,6.12,6.18,unpinned)
#   AL2023_PARTIAL=1     allow a narrowed run: fewer kernel groups or tags, or a
#                        profile subset. Without it, judge requires the full
#                        set (every group, all 4 profiles: exactly AL2023_FULL_ROWS
#                        rows) and `all` refuses tags or a narrowed selection.
#   AL2023_BURNIN        burn-in only (guest.sh); the run is then always red
#   G035_BPFTOOL_TARBALL bpftool-v7.8.1-amd64.tar.gz (checked by sha256; downloaded
#                        from the libbpf/bpftool release when unset)
#
# <run-dir> must not exist for build (evidence is never overwritten); every
# later step writes only new files under it. Results: <run-dir>/results/<group>/
# (test2json streams, infra.tsv, evidence/), <run-dir>/results.tsv and
# <run-dir>/verdict.txt.
set -uo pipefail
# Build with the module of this checkout only (a go.work outside it must not
# change what is built).
export GOWORK=off

HERE=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
REPO=$(cd -- "$HERE/../../../.." && pwd)
# shellcheck source=env.sh
. "$HERE/env.sh"
BPFTOOL_URL=https://github.com/libbpf/bpftool/releases/download/v7.8.1/bpftool-v7.8.1-amd64.tar.gz
BPFTOOL_SHA256=112026bbdf48d0d00ccfc4926e59878d47943f97c197f959f110abe29c898ddc
FULL_KERNELS=build,6.12,6.18,unpinned
# The full run's row count (expected.tsv with every group and profile).
AL2023_FULL_ROWS=145

die() { echo "host.sh: $*" >&2; exit 2; }
log() { echo "[host.sh $(date -u +%T)] $*"; }

# infra name rc detail: one infrastructure step of the current group
# (INFRA is the group's infra.tsv). A nonzero rc makes the judge red.
infra() {
	printf '%s\t%s\t%s\n' "$1" "$2" "${3//$'\t'/ }" >>"$INFRA"
	[[ $2 == 0 ]] || log "INFRA FAIL $1 ($2): $3"
}

# derive_product_pins <tsv>: AL2023_PRODUCT_ELF_SHA256[<kernel>:<profile>]
# as a bash declaration. The tsv must exist and hold exactly 8 object pins:
# one line per kernel of env.sh (release in column 1), 4 sha256 (the
# objects qualified on that kernel) in column 4 in profile order
# AL2023_ALL_PROFILES.
derive_product_pins() {
	local tsv=$1 release _ k n=0 i p seen=
	local -a shas profiles
	[[ -f $tsv ]] || { echo "host.sh: $tsv is missing" >&2; return 1; }
	read -ra profiles <<<"$AL2023_ALL_PROFILES"
	echo "# Generated by host.sh build from $(basename -- "$tsv") (sha256 $(sha256sum "$tsv" | cut -d' ' -f1)); do not edit."
	echo "declare -A AL2023_PRODUCT_ELF_SHA256=("
	while IFS=$'\t' read -r release _ _ list; do
		[[ -z $release || $release == '#'* ]] && continue
		k=
		for kk in $AL2023_KERNELS; do [[ ${AL2023_RELEASE[$kk]} == "$release" ]] && k=$kk; done
		[[ -n $k ]] || { echo "host.sh: $tsv: release $release is not a kernel of env.sh" >&2; return 1; }
		[[ " $seen " != *" $k "* ]] || { echo "host.sh: $tsv: release $release twice" >&2; return 1; }
		seen+=" $k"
		IFS=, read -ra shas <<<"$list"
		[[ ${#shas[@]} == "${#profiles[@]}" ]] || { echo "host.sh: $tsv: $release has ${#shas[@]} object pins, want ${#profiles[@]}" >&2; return 1; }
		for i in "${!profiles[@]}"; do
			[[ ${shas[$i]} =~ ^[0-9a-f]{64}$ ]] || { echo "host.sh: $tsv: bad sha256 ${shas[$i]}" >&2; return 1; }
			p=${profiles[$i]}
			echo "	[$k:$p]=${shas[$i]}"
			n=$((n + 1))
		done
	done <"$tsv"
	echo ")"
	[[ $n == 8 ]] || { echo "host.sh: $tsv: $n object pins, want 8" >&2; return 1; }
}

require_config() {
	al2023_require_profiles || exit 2
	al2023_require_neg_set || exit 2
}

cmd_build() {
	local rd=$1 b R J obj objs rc
	[[ ! -e $rd ]] || die "$rd exists (never overwrite evidence)"
	require_config
	mkdir -p "$rd/bundle/bin" "$rd/bundle/objects" "$rd/results/build/evidence" "$rd/build" || die "mkdir $rd"
	rd=$(cd -- "$rd" && pwd)
	b=$rd/bundle R=$rd/results/build INFRA=$rd/results/build/infra.tsv
	tr -c 'a-z0-9-\n' '-' <<<"$(basename -- "$rd" | tr 'A-Z' 'a-z')" | cut -c1-40 >"$rd/run-id"
	cd -- "$REPO" || die "cd $REPO"
	git rev-parse HEAD >"$R/evidence/git-head.txt" 2>/dev/null
	git status --porcelain >"$R/evidence/git-status.txt" 2>/dev/null

	# The judge first: it writes the harness rows.
	CGO_ENABLED=0 go build -o "$b/bin/judge" ./gadgets/enforce_exec/test/al2023-product-load/judge
	rc=$?
	infra judge "$rc" "go build judge"
	J=$b/bin/judge
	[[ $rc == 0 ]] || return 1

	# The object pins, derived from the source of truth (never duplicated).
	derive_product_pins "$REPO/gadgets/enforce_exec/fullruntime/testdata/shared_product_pins.tsv" >"$b/product-pins.sh"
	rc=$?
	infra pins "$rc" "product-pins.sh from testdata/shared_product_pins.tsv"
	[[ $rc == 0 ]] || return 1
	cp -- "$b/product-pins.sh" "$R/evidence/"

	log "product objects (pinned container)"
	make -C "$REPO" enforce-exec-product-objects ENFORCE_EXEC_PRODUCT_OUT="$rd/build/objects" >"$R/evidence/build-product.log" 2>&1
	rc=$?
	infra objects "$rc" "make enforce-exec-product-objects (build-product.sh --check)"
	local S=$R/objects__-.json name status
	while read -r status name sum _; do
		[[ $status == OK || $status == FAIL ]] || continue
		"$J" row -stream "$S" -test "pin/$name" -status "$([[ $status == OK ]] && echo pass || echo fail)" -detail "$status $name ${sum%,}"
	done <"$R/evidence/build-product.log"
	[[ -s $S ]] && "$J" end -stream "$S"
	objs=()
	# Stage 1: one CO-RE object per profile, shared by every kernel.
	for p in $AL2023_ALL_PROFILES; do
		obj=$rd/build/objects/$(al2023_object - "$p")
		cp -- "$obj" "$b/objects/" && objs+=("$b/objects/$(basename -- "$obj")")
	done
	sha256sum "${objs[@]}" | sed "s|$b/||" >"$R/evidence/objects.sha256"
	local list
	list=$(IFS=,; echo "${objs[*]}")

	log "OCI layout (tag-only builder, twice)"
	IG_ENFORCE_EXEC_PRODUCT_OBJECTS=$list IG_SHARED_PRODUCT_LAYOUT_OUT=$rd/build/layout-1 \
		go test -json -count=1 -tags 'enforce_exec_shared_qualification enforce_exec_product_layout' -run '^TestBuildSharedProductLayout$' ./gadgets/enforce_exec/fullruntime >"$R/layout__-.json" 2>"$R/evidence/layout.stderr"
	infra layout $? "TestBuildSharedProductLayout"
	IG_ENFORCE_EXEC_PRODUCT_OBJECTS=$list IG_SHARED_PRODUCT_LAYOUT_OUT=$rd/build/layout-2 \
		go test -count=1 -tags 'enforce_exec_shared_qualification enforce_exec_product_layout' -run '^TestBuildSharedProductLayout$' ./gadgets/enforce_exec/fullruntime >"$R/evidence/layout-2.log" 2>&1
	infra layout-2 $? "TestBuildSharedProductLayout, second process"
	S=$R/layout-repro__-.json
	if diff -r "$rd/build/layout-1" "$rd/build/layout-2" >"$R/evidence/layout-diff.txt" 2>&1; then
		"$J" row -stream "$S" -test rebuild_identical -status pass -detail "index.json sha256 $(sha256sum "$rd/build/layout-1/layout/index.json" | cut -d' ' -f1), identical in a second process"
	else
		"$J" row -stream "$S" -test rebuild_identical -status fail -detail "layouts differ: $(head -c 300 "$R/evidence/layout-diff.txt")"
	fi
	"$J" end -stream "$S"
	cp -a -- "$rd/build/layout-1/layout" "$rd/build/layout-1/images.tsv" "$rd/build/layout-1/layout.sha256sums" "$b/"
	infra layout-copy $? "layout into the bundle"
	cp -- "$rd/build/layout-1/images.tsv" "$rd/build/layout-1/layout.sha256sums" "$R/evidence/"

	log "userspace object checks"
	IG_ENFORCE_EXEC_PRODUCT_OBJECTS=$list go test -json -count=1 \
		-run '^(TestSharedProductManifestMatchesObjects|TestCandidateAttachSetObjects|TestSharedCandidateMergedMetadataObjects)$' \
		./gadgets/enforce_exec/fullruntime >"$R/userspace__-.json" 2>"$R/evidence/userspace.stderr"
	infra userspace $? "userspace object checks"

	log "binaries"
	CGO_ENABLED=0 go test -c -o "$b/bin/fullruntime.test" ./gadgets/enforce_exec/fullruntime
	infra test-binary $? "go test -c ./gadgets/enforce_exec/fullruntime (product build, no tag)"
	CGO_ENABLED=0 go build -o "$b/bin/verdict-load" ./gadgets/enforce_exec/test/al2023-verdict-load
	infra verdict-load $? "go build al2023-verdict-load"
	CGO_ENABLED=0 go build -o "$b/bin/test2json" cmd/test2json
	infra test2json $? "go build cmd/test2json"
	local tarball=${G035_BPFTOOL_TARBALL:-$rd/build/bpftool-v7.8.1-amd64.tar.gz}
	[[ -f $tarball ]] || curl -fsSL --retry 3 -o "$tarball" "$BPFTOOL_URL"
	if [[ $(sha256sum "$tarball" 2>/dev/null | cut -d' ' -f1) == "$BPFTOOL_SHA256" ]]; then
		tar -xzf "$tarball" -C "$b/bin" bpftool && chmod +x "$b/bin/bpftool"
		infra bpftool $? "bpftool v7.8.1 (tarball sha256 $BPFTOOL_SHA256)"
	else
		infra bpftool 1 "bpftool tarball $tarball does not match sha256 $BPFTOOL_SHA256"
	fi
	cp -- "$HERE/env.sh" "$HERE/guest.sh" "$b/" && chmod +x "$b/guest.sh"
	infra harness $? "env.sh and guest.sh"
	(cd -- "$b" && find . -type f ! -name bundle.sha256sums -print0 | LC_ALL=C sort -z | xargs -0 sha256sum >bundle.sha256sums)
	infra manifest $? "bundle.sha256sums"
	cp -- "$b/bundle.sha256sums" "$R/evidence/"
	log "bundle $b ($(du -sh "$b" | cut -f1)), bundle.sha256sums $(sha256sum "$b/bundle.sha256sums" | cut -d' ' -f1)"
	if awk -F'\t' '$2 != 0 { bad = 1 } END { exit !bad }' "$INFRA"; then
		log "build failed: $(awk -F'\t' '$2 != 0 { printf "%s ", $1 }' "$INFRA")"
		return 1
	fi
}

# full_selection: is this the full run (every group, all 4 profiles)?
full_selection() {
	[[ ${AL2023_JUDGE_KERNELS:-$FULL_KERNELS} == "$FULL_KERNELS" && $AL2023_PROFILES == "$AL2023_ALL_PROFILES" ]]
}

cmd_run() {
	local rd=$1 lane=$2 tag=$3 stage rc
	[[ -d $rd/bundle && -f $rd/run-id ]] || die "$rd has no bundle (host.sh build first)"
	rd=$(cd -- "$rd" && pwd)
	[[ -f $HERE/lanes/$lane.sh ]] || die "unknown lane $lane"
	case $tag in 6.12 | 6.18 | unpinned) ;; *) die "unknown tag $tag" ;; esac
	[[ ! -e $rd/results/$tag && ! -e $rd/lane/$tag ]] || die "$tag already ran in $rd"
	require_config
	AL2023_RUN=$(cat "$rd/run-id")
	export AL2023_PROFILES AL2023_NEG_SET AL2023_RUN AL2023_BURNIN=${AL2023_BURNIN:-}
	stage=$rd/lane/$tag
	mkdir -p "$stage" || die "mkdir $stage"
	INFRA=$stage/infra.tsv
	# shellcheck source=/dev/null
	. "$HERE/lanes/$lane.sh"
	log "lane $lane: $tag"
	if lane_preflight; then
		infra preflight 0 "lane $lane"
		lane_run "$tag" "$rd/bundle" "$stage"
		lane_down "$tag" "$stage"
		lane_prove_absence "$tag" "$stage"
	else
		infra preflight 1 "lane $lane refused (see the log)"
	fi
	# The guest's results become results/<tag>; the infra record and the
	# lane's evidence go with them (a run without results still leaves
	# its infra record, so the judge reports it).
	if [[ -d $stage/out/$tag ]]; then cp -a -- "$stage/out/$tag" "$rd/results/"; else mkdir -p "$rd/results/$tag/evidence"; fi
	mkdir -p "$rd/results/$tag/evidence/lane"
	cp -- "$stage/infra.tsv" "$rd/results/$tag/infra.tsv"
	for f in run-manifest.json console.log qemu.log guest/driver.log guest/payload.log guest/dmesg.txt; do
		[[ -f $stage/lane/vm/$f ]] && cp -- "$stage/lane/vm/$f" "$rd/results/$tag/evidence/lane/"
	done
	log "lane $lane: $tag done ($(awk -F'\t' '$2 != 0' "$INFRA" | wc -l) infra failures)"
}

cmd_judge() {
	local rd=$1 rc profiles pin=()
	require_config
	profiles=$(tr ' ' ',' <<<"$AL2023_PROFILES")
	if full_selection; then
		pin=(-rows "$AL2023_FULL_ROWS")
	elif [[ ${AL2023_PARTIAL:-} != 1 ]]; then
		die "a narrowed judge (AL2023_JUDGE_KERNELS or AL2023_PROFILES) needs AL2023_PARTIAL=1"
	fi
	"$rd/bundle/bin/judge" check -expected "$HERE/expected.tsv" -results "$rd/results" \
		-kernels "${AL2023_JUDGE_KERNELS:-$FULL_KERNELS}" -profiles "$profiles" "${pin[@]}" -out "$rd/results.tsv" >"$rd/verdict.txt" 2>&1
	rc=$?
	cat "$rd/verdict.txt"
	return "$rc"
}

[[ $# -ge 2 ]] || die "usage: host.sh build|run|judge|all <run-dir> ..."
case $1 in
build) cmd_build "$2" ;;
run)
	[[ $# -eq 4 ]] || die "usage: host.sh run <run-dir> <lane> <tag>"
	cmd_run "$2" "$3" "$4"
	;;
judge) cmd_judge "$2" ;;
all)
	[[ $# -ge 3 ]] || die "usage: host.sh all <run-dir> <lane> [tag...]"
	rd=$2 lane=$3
	shift 3
	tags=("$@")
	if ((${#tags[@]})) || ! full_selection; then
		[[ ${AL2023_PARTIAL:-} == 1 ]] || die "all: tags or a narrowed selection need AL2023_PARTIAL=1"
	fi
	((${#tags[@]})) || tags=(6.12 6.18 unpinned)
	cmd_build "$rd" || die "build failed (see $rd/results/build/infra.tsv); no lane runs"
	for t in "${tags[@]}"; do (cmd_run "$rd" "$lane" "$t"); done
	cmd_judge "$rd"
	;;
*) die "unknown command $1" ;;
esac
